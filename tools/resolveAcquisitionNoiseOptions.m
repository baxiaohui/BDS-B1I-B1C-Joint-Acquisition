function cfg = resolveAcquisitionNoiseOptions(cfg)
% Missing noise options mean disabled for existing direct helper callers.
defaults=struct('enabled',false,'cn0DropDb',0,'seed',20261102, ...
    'calibrationMs',50,'calibrationMode','code-spectrum','originalNoisePsd',[],'referenceCN0dBHz',[]);
if ~isfield(cfg,'noise'), cfg.noise=struct(); end
assert(isstruct(cfg.noise) && isscalar(cfg.noise),'noise must be a scalar struct.');
for f=fieldnames(defaults).'
    if ~isfield(cfg.noise,f{1}), cfg.noise.(f{1})=defaults.(f{1}); end
end
n=cfg.noise;
mode=lower(string(n.calibrationMode));
assert(isscalar(mode) && ismember(mode,["code-spectrum","bandpower"]), ...
    'noise.calibrationMode must be code-spectrum or bandpower.');
n.calibrationMode=char(mode);
assert(isscalar(n.enabled) && (islogical(n.enabled) || isnumeric(n.enabled)) && ...
    isreal(n.enabled) && ismember(n.enabled,[0 1]),'noise.enabled must be true or false.');
assert(isnumeric(n.cn0DropDb) && isreal(n.cn0DropDb) && isscalar(n.cn0DropDb) && ...
    isfinite(n.cn0DropDb) && n.cn0DropDb>=0 && n.cn0DropDb<=300, ...
    'noise.cn0DropDb must be a finite scalar in [0,300] dB.');
assert(isnumeric(n.seed) && isreal(n.seed) && isscalar(n.seed) && isfinite(n.seed) && ...
    n.seed==fix(n.seed) && n.seed>=0 && n.seed<=2^32-1, ...
    'noise.seed must be an integer in [0,2^32-1].');
assert(isnumeric(n.calibrationMs) && isreal(n.calibrationMs) && isscalar(n.calibrationMs) && ...
    isfinite(n.calibrationMs) && n.calibrationMs>=1 && n.calibrationMs<=1000, ...
    'noise.calibrationMs must be in [1,1000] ms.');
for f={'originalNoisePsd','referenceCN0dBHz'}
    v=n.(f{1});
    assert(isempty(v) || (isnumeric(v) && isreal(v) && isvector(v) && ...
        numel(v)==2 && all(isfinite(v))), ...
        'noise.%s must be [] or [B1I B1C].',f{1});
    if ~isempty(v), n.(f{1})=double(v(:).'); end
end
assert(isempty(n.originalNoisePsd) || all(n.originalNoisePsd>0), ...
    'noise.originalNoisePsd must be positive in unpacked sample units squared/Hz.');
n.enabled=logical(n.enabled); cfg.noise=n;
end
