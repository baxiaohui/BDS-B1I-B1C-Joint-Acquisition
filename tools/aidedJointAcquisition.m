function results = aidedJointAcquisition(cfg)
% Arbitrary positive receive-time integration for B1I / B1C / joint search.
% Known signs are inside the matched filters, including fractional tails.
root=fileparts(fileparts(mfilename('fullpath'))); old=path;
restore=onCleanup(@()path(old));
addpath(fullfile(root,'tools'),fullfile(root,'mBDS_B1I','include'), ...
    fullfile(root,'mBDS-3_B1C','include'));
defaults=struct('autoDopplerStep',true,'codeDriftCompensation',true, ...
    'dopplerRateHzPerSecond',0,'fftSegmentMs',20,'frequencyBatchSize',8, ...
    'maxWorkingCacheMB',256,'maxSurfaceCodeColumns',1000, ...
    'maxSurfaceFrequencyRows',301,'useGPU','auto');
for f=fieldnames(defaults).'
    if ~isfield(cfg,f{1}), cfg.(f{1})=defaults.(f{1}); end
end
cfg=resolveJointAcquisitionOptions(cfg);
cfg=resolveAcquisitionNoiseOptions(cfg);
assert(cfg.startSecond>=0 && cfg.startSecond+(cfg.maxCoherentMs+11)/1000<=cfg.durationSeconds, ...
    'Requested coherent duration plus code-phase search/lookahead exceeds B.');
assert(all(cfg.prnList>=6 & cfg.prnList<=58),'NH-assisted joint mode requires D1 PRNs 6:58.');
assert(isvector(cfg.dopplerHz) && ~isempty(cfg.dopplerHz) && all(isfinite(cfg.dopplerHz)),'Invalid Doppler grid.');
assert(isscalar(cfg.dopplerRateHzPerSecond) && isfinite(cfg.dopplerRateHzPerSecond),'Invalid Doppler rate.');
assert(cfg.fftSegmentMs>0 && cfg.maxWorkingCacheMB>0 && ...
    cfg.frequencyBatchSize>=1 && mod(cfg.frequencyBatchSize,1)==0,'Invalid FFT/cache settings.');
assert(cfg.maxSurfaceCodeColumns>=2 && cfg.maxSurfaceFrequencyRows>=2,'Invalid surface size.');
if ~isfolder(cfg.resultsDir), mkdir(cfg.resultsDir); end
cfg.workCacheDir=fullfile(root,'cache','joint_work');
if ~isfolder(cfg.workCacheDir), mkdir(cfg.workCacheDir); end
cfg.gpuEnabled=selectGPU(cfg.useGPU);
fs=14.5e6;
fdC=sort(unique(double(cfg.dopplerHz(:)))); requestedFD=fdC;
maxStep=0.5/(cfg.maxCoherentMs/1000);
if numel(fdC)>1 && max(diff(fdC))>maxStep*(1+1e-10)
    if cfg.autoDopplerStep
        dense=[];
        for k=1:numel(fdC)-1
            count=ceil((fdC(k+1)-fdC(k))/maxStep);
            section=linspace(fdC(k),fdC(k+1),count+1).';
            dense=[dense;section(1:end-1)]; %#ok<AGROW>
        end
        fdC=[dense;fdC(end)];
        fprintf('Doppler grid refined: %d -> %d bins, maximum step %.6g Hz for max(TI,TC)=%.9g ms.\n', ...
            numel(requestedFD),numel(fdC),max(diff(fdC)),cfg.maxCoherentMs);
    else
        warning('LongCoherent:FrequencyGrid','Grid step exceeds 0.5/T; long integration may cancel from frequency mismatch.');
    end
end
% All aids are validated before weak samples are read or searched.
aids=cell(size(cfg.prnList));
for k=1:numel(cfg.prnList), aids{k}=loadAids(cfg,cfg.prnList(k)); end
% Calibrate ONCE from unmodified samples, then share one absolute-indexed
% realization across all satellites, standalone searches and joint search.
cfg.weakNoiseModel=prepareAcquisitionNoise(cfg);
noise=cfg.weakNoiseModel;
results=struct([]);
for ip=1:numel(cfg.prnList)
    prn=cfg.prnList(ip); cfg.currentPRN=prn;
    fprintf('B %.6f s C%02d: TI=%.9g ms, TC=%.9g ms; weights=[%g %g] (%s); %s; GPU=%d.\n', ...
        cfg.startSecond,prn,cfg.b1iCoherentMs,cfg.b1cCoherentMs,cfg.jointWeights(1),cfg.jointWeights(2), ...
        cfg.jointWeightNormalization,cfg.b1cBranch,cfg.gpuEnabled);
    [parts,warp,preparation,cleanup]=prepareCoherentParts(cfg,aids{ip},fs);
    [maps,best,search]=coherentFftSearch(parts,fs,fdC,cfg);
    clear parts cleanup;
    h=preparation.NHIndex-1;
    uI=best.I.sample/fs; uC=best.C.sample/fs; uJ=best.J.sample/fs;
    uCW=best.C.windowSample/fs; % Full C code phase is NOT the window start.
    uJC=mod(uJ-mod(h,10)*0.001,0.010);
    durationI=preparation.codeSamplesI/fs;
    durationCJ=preparation.codeSamplesCJ/fs;
    durationCF=preparation.codeSamplesCF/fs;
    % Joint detection depends ONLY on its global maximum score. Individual
    % branch detections and powers are diagnostics, never additional gates.
    jointDetected=best.J.score>=cfg.minJointScore;
    rec=struct('PRN',prn,'BStartSecond',cfg.startSecond, ...
        'B1ICoherentMs',cfg.b1iCoherentMs,'B1CCoherentMs',cfg.b1cCoherentMs, ...
        'B1CBranch',cfg.b1cBranch, ...
        'B1CDataAmplitudeWeight',cfg.b1cEffectiveDataPilotWeights(1), ...
        'B1CPilot11AmplitudeWeight',cfg.b1cEffectiveDataPilotWeights(2), ...
        'B1CPilotSignalPhaseDeg',cfg.b1cPilotPhaseDeg, ...
        'B1CPilotModel','BOC11 only', ...
        'B1CWindowMode','shared-candidate','B1CBackgroundShared',true, ...
        'NHIndex',h+1,'B1ICodeMs',rxTime(warp,uI)*1000, ...
        'B1ICodeTimeMs',uI*1000,'B1CCodeTimeMs',uC*1000,'jointCodeTimeMs',uJ*1000, ...
        'B1IDopplerHz',fdC(best.I.frequency)*1561.098/1575.42,'B1IRatio',best.I.score, ...
        'B1IDetected',best.I.score>=cfg.b1iMinRatio, ...
        'B1CCodeMs',rxTime(warp,uC)*1000,'B1CDopplerHz',fdC(best.C.frequency), ...
        'B1CRatio',best.C.score,'B1CDetected',best.C.score>=cfg.b1cMinRatio, ...
        'jointCodeMs',rxTime(warp,uJ)*1000,'jointB1CCodeMs',rxTime(warp,uJC)*1000, ...
        'jointB1CDopplerHz',fdC(best.J.frequency),'jointScore',best.J.score, ...
        'jointB1IRatio',best.J.ratioI,'jointB1CRatio',best.J.ratioC, ...
        'phaseCompRad',best.J.theta,'jointDetected',jointDetected, ...
        'phaseCompDeg',mod(best.J.theta*180/pi,360), ...
        'phaseDifferenceRad',best.J.phaseDifference, ...
        'phaseQuantizationErrorDeg',best.J.phaseError*180/pi, ...
        'phaseCandidateIndex',best.J.phaseIndex, ...
        'jointPhaseMode',cfg.jointPhaseMode,'jointPhaseBins',cfg.jointPhaseEffectiveBins, ...
        'jointPhaseStepDeg',cfg.jointPhaseStepDeg, ...
        'jointPhaseMaxQuantizationErrorDeg',cfg.jointPhaseMaxQuantizationErrorDeg, ...
        'B1IActualCoherentMs',(rxTime(warp,uI+durationI)-rxTime(warp,uI))*1000, ...
        'B1CActualCoherentMs',(rxTime(warp,uCW+durationCF)-rxTime(warp,uCW))*1000, ...
        'jointB1IActualCoherentMs',(rxTime(warp,uJ+durationI)-rxTime(warp,uJ))*1000, ...
        'jointB1CActualCoherentMs',(rxTime(warp,uJ+durationCJ)-rxTime(warp,uJ))*1000, ...
        'B1IWindowStartSecond',cfg.startSecond+rxTime(warp,uI), ...
        'B1IWindowEndSecond',cfg.startSecond+rxTime(warp,uI+durationI), ...
        'B1CWindowStartSecond',cfg.startSecond+rxTime(warp,uCW), ...
        'B1CWindowEndSecond',cfg.startSecond+rxTime(warp,uCW+durationCF), ...
        'jointB1CWindowStartSecond',cfg.startSecond+rxTime(warp,uJ), ...
        'jointB1CWindowEndSecond',cfg.startSecond+rxTime(warp,uJ+durationCJ), ...
        'coherentCodeSamplesI',preparation.codeSamplesI, ...
        'coherentCodeSamplesCJ',preparation.codeSamplesCJ,'coherentCodeSamplesCF',preparation.codeSamplesCF, ...
        'jointWeightB1I',cfg.jointWeights(1),'jointWeightB1C',cfg.jointWeights(2), ...
        'jointEffectiveWeightB1I',cfg.jointEffectiveWeights(1), ...
        'jointEffectiveWeightB1C',cfg.jointEffectiveWeights(2), ...
        'jointWeightNormalization',cfg.jointWeightNormalization, ...
        'B1IThreshold',cfg.b1iMinRatio,'B1CThreshold',cfg.b1cMinRatio, ...
        'jointThreshold',cfg.minJointScore,'jointDecisionRule','jointScore only', ...
        'dopplerBins',numel(fdC), ...
        'noiseEnabled',noise.enabled,'CN0DropDb',noise.appliedDropDb, ...
        'noiseSeed',noise.seed,'noiseCalibrationMethod',noise.calibrationMethod, ...
        'noiseCalibrationMode',noise.calibrationMode, ...
        'noiseCalibrationMs',noise.calibrationMs, ...
        'originalNoisePsdB1I',noise.originalNoisePsd(1), ...
        'originalNoisePsdB1C',noise.originalNoisePsd(2), ...
        'addedNoisePsdB1I',noise.addedNoisePsd(1), ...
        'addedNoisePsdB1C',noise.addedNoisePsd(2), ...
        'codeDriftCompensation',cfg.codeDriftCompensation,'gpuEnabled',cfg.gpuEnabled);
    if isempty(results), results=rec; else, results(end+1)=rec; end %#ok<AGROW>
    fprintf('C%02d: I %.2f @ %.6f ms; C %.2f @ %.6f ms; joint %.2f @ %.6f ms (%d).\n', ...
        prn,rec.B1IRatio,rec.B1ICodeMs,rec.B1CRatio,rec.B1CCodeMs,rec.jointScore,rec.jointCodeMs,rec.jointDetected);
    token=sprintf('TI%gms_TC%gms_wI%g_wC%g_%s',cfg.b1iCoherentMs,cfg.b1cCoherentMs, ...
        cfg.jointWeights(1),cfg.jointWeights(2),cfg.jointWeightNormalization);
    if strcmp(cfg.b1cBranch,'both')
        token=[token sprintf('_d%.6g_p%.6g_ph%g',cfg.b1cEffectiveDataPilotWeights,cfg.b1cPilotPhaseDeg)];
    end
    token=[token '_sharedWin'];
    if strcmp(cfg.jointPhaseMode,'grid')
        phaseLabel=sprintf('grid K=%g, step=%g deg',cfg.jointPhaseBins,cfg.jointPhaseStepDeg);
        token=[token sprintf('_phaseGridK%g',cfg.jointPhaseBins)];
    else
        phaseLabel='continuous phase optimum';
        token=[token '_phaseContinuous'];
    end
    if noise.enabled
        token=[token sprintf('_cn0Drop%gdB_seed%u',noise.appliedDropDb,noise.seed)];
        if strcmp(noise.calibrationMethod,'manual originalNoisePsd')
            token=[token '_nCalManual'];
        elseif strcmp(noise.calibrationMode,'code-spectrum')
            token=[token '_nCalCode'];
        else
            token=[token '_nCalBand'];
        end
    else
        token=[token '_noiseOff'];
    end
    fprintf('  joint phase: %s; applied %.9g deg; quantization residual %.9g deg.\n', ...
        phaseLabel,rec.phaseCompDeg,rec.phaseQuantizationErrorDeg);
    name=sprintf('B_%.3fs_C%02d_%s_%s',cfg.startSecond,prn,cfg.b1cBranch,token);
    cache=fullfile(root,'cache','joint_acquisition'); if ~isfolder(cache), mkdir(cache); end
    save(fullfile(cache,[name '.mat']),'maps','best','fdC','requestedFD','fs','rec','cfg','preparation','search','-v7.3');
    % Configurable two 1x3 or one 2x3 composite, without popup labels.
    plotAidedAcquisitionFigures(maps,rec,cfg,name);
end
writetable(struct2table(results),fullfile(cfg.resultsDir,sprintf('B_%.3fs_%s_%s_results.csv',cfg.startSecond,cfg.b1cBranch,token)),'Encoding','UTF-8');
end
function t=rxTime(warp,u)
t=interp1(warp.u,warp.t,u,'linear');
assert(all(isfinite(t)),'Code-time conversion exceeds aid coverage.');
end
function gpu=selectGPU(option)
request=lower(string(option));
assert(ismember(request,["auto","true","false","gpu","cpu","1","0"]),'useGPU must be auto, true/false, gpu/cpu.');
gpu=false;
if ismember(request,["false","cpu","0"]), return; end
try
    gpu=exist('gpuDeviceCount','file') && gpuDeviceCount>0;
    if gpu, device=gpuDevice(); gpu=device.AvailableMemory>512*1024^2; end
catch
    gpu=false;
end
if ~gpu && ismember(request,["true","gpu","1"])
    error('GPU requested but unavailable or insufficient free memory. Set useGPU=false for CPU.');
end
end

function aid=loadAids(cfg,prn)
baseI=fullfile(cfg.aidDir,'B1I',sprintf('B1I_PRN%02d',prn));
baseC=fullfile(cfg.aidDir,'B1C',sprintf('B1C_PRN%02d',prn));
required={[baseI '_data_bits.txt'],[baseI '_NH.txt'], ...
    [baseC '_data_bits.txt'],[baseC '_secondary_code.txt']};
for k=1:numel(required)
    assert(isfile(required{k}), ...
        ['C%02d aligned aids are missing: %s. Run run_ab_stripping with this PRN first, ' ...
         'or set acquisition.prnList to satellites whose aligned aids already exist.'],prn,required{k});
end
aid.dataI=readStrippingAid([baseI '_data_bits.txt']);
aid.nh=readStrippingAid([baseI '_NH.txt']);
aid.dataC=readStrippingAid([baseC '_data_bits.txt']);
aid.secondary=readStrippingAid([baseC '_secondary_code.txt']);
info=readLabsat3wInfo(cfg.ls3wFile); names=fieldnames(aid);
for k=1:numel(names)
    a=aid.(names{k});
    source=regexp(a.header,'(?m)^# B_SOURCE=([^\r\n]*)','tokens','once');
    assert(~isempty(source) && strcmpi(strtrim(source{1}),char(java.io.File(cfg.ls3wFile).getCanonicalPath())), ...
        'Aid belongs to another B source: %s',a.file);
    bytes=number(a.header,'B_FILE_BYTES'); stamp=number(a.header,'B_FILE_DATENUM');
    assert(bytes==info.fileBytes && abs(stamp-info.modifiedDatenum)<1e-9,'B recording changed since aid export.');
    assert(abs(number(a.header,'B_FILE_START_SECONDS')-cfg.fileStartSecond)<1/info.SMP, ...
        'Aid B start does not match fileStartSecond.');
    assert(abs(number(a.header,'B_DURATION_SECONDS')-cfg.durationSeconds)<1e-6,'Aid B duration mismatch.');
    % Check real intervals, including internal gaps, over the ENTIRE read.
    begin=cfg.startSecond;
    if strcmp(names{k},'nh'), needed=cfg.maxCoherentMs;
    elseif strcmp(names{k},'dataI'), needed=cfg.b1iCoherentMs;
    else, needed=cfg.b1cCoherentMs; end
    finish=begin+(needed+11)/1000;
    rows=a.rows(a.rows(:,6)>begin & a.rows(:,4)<finish,:);
    cursor=begin;
    for j=1:size(rows,1)
        assert(rows(j,4)<=cursor+2e-6,'Aid gap at B %.9f s: %s',cursor,a.file);
        cursor=max(cursor,rows(j,6));
    end
    assert(cursor>=finish-2e-6,'Insufficient aid coverage for requested weak window: %s',a.file);
end
end
function value=number(header,key)
tok=regexp(header,[key '=([-+\d.eE]+)'],'tokens','once');
assert(~isempty(tok),'Missing aid metadata: %s',key); value=str2double(tok{1});
end
